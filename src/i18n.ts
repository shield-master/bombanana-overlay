const DICTS: Record<Locale, Dict> = { en, ru, es, fr, de, zh, ja };

let current: Locale = "en";
const listeners = new Set<() => void>();

/** Определяет язык по системным настройкам (navigator.languages), en — если совпадений нет. */
export function detectSystemLocale(): Locale {
  const candidates = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const raw of candidates) {
    const base = raw.toLowerCase().split("-")[0];
    if ((LOCALES as string[]).includes(base)) return base as Locale;
  }
  return "en";
}

export function getLocale(): Locale {
  return current;
}

/** Меняет язык и уведомляет подписчиков (используется при живом переключении из UI). */
export function setLocale(locale: Locale): void {
  if (current === locale) return;
  current = locale;
  for (const fn of listeners) fn();
}

/** Выставляет язык без уведомления — только для старта бутстрапа. */
export function initLocale(locale: Locale): void {
  current = locale;
}

export function onLocaleChange(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const raw = DICTS[current][key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** Применяет data-i18n/-placeholder/-title атрибуты в поддереве — статичная разметка home-экрана. */
export function applyI18n(root: ParentNode): void {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (key && el instanceof HTMLInputElement) el.placeholder = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    const key = el.dataset.i18nTitle;
    if (key) el.title = t(key);
  });
}
